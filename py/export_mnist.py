"""
导出 100 张 MNIST 测试图（每类 10 张，随机采样）到 C 头文件
用法: python export_mnist_100.py
输出: mnist_100.h
换一批图片: 改 RANDOM_SEED
"""

import numpy as np
from torchvision import datasets, transforms

NUM_PER_CLASS = 1
NUM_CLASSES   = 10
TOTAL         = NUM_PER_CLASS * NUM_CLASSES
RANDOM_SEED   = 10         # ← 改这个数字就换一批图

def main():
    transform = transforms.Compose([transforms.ToTensor()])
    test_set = datasets.MNIST('./data', train=False, download=True, transform=transform)

    # 1. 建立每类的索引列表
    indices_by_class = {i: [] for i in range(NUM_CLASSES)}
    for idx, (_, label) in enumerate(test_set):
        indices_by_class[label].append(idx)

    # 2. 用种子随机挑
    rng = np.random.default_rng(RANDOM_SEED)
    chosen_indices = []
    for c in range(NUM_CLASSES):
        picked = rng.choice(indices_by_class[c], NUM_PER_CLASS, replace=False)
        chosen_indices.extend(sorted(picked.tolist()))

    # 3. 按索引取图
    images = []
    labels = []
    for idx in chosen_indices:
        img, label = test_set[idx]
        arr = (img[0].numpy() * 255).round().astype(np.uint8)
        images.append(arr)
        labels.append(int(label))

    assert len(images) == TOTAL

    # 4. 写头文件
    with open('mnist_100.h', 'w') as f:
        f.write('// Auto-generated by export_mnist_100.py\n')
        f.write(f'// Seed={RANDOM_SEED}, {NUM_PER_CLASS}/class, {TOTAL} total\n')
        f.write('#ifndef MNIST_100_H\n#define MNIST_100_H\n\n')
        f.write('#include <stdint.h>\n\n')

        f.write(f'static const unsigned char mnist_100[{TOTAL}][28][28] = {{\n')
        for i in range(TOTAL):
            f.write(f'  {{ // #{i}, label={labels[i]}\n')
            for r in range(28):
                row = ', '.join(f'{int(v):3d}' for v in images[i][r])
                f.write(f'    {{{row}}},\n')
            f.write('  },\n')
        f.write('};\n\n')

        f.write(f'static const unsigned char mnist_100_labels[{TOTAL}] = {{\n')
        for i in range(0, TOTAL, 20):
            chunk = labels[i:i+20]
            f.write('  ' + ', '.join(f'{v:2d}' for v in chunk) + ',\n')
        f.write('};\n\n')

        f.write('#endif // MNIST_100_H\n')

    print(f'[OK] 导出 {TOTAL} 张图到 mnist_100.h')
    print(f'     RANDOM_SEED = {RANDOM_SEED}')
    print(f'     每类 {NUM_PER_CLASS} 张')

if __name__ == '__main__':
    main()