"""
把一张图片转成 C 数组（MNIST 格式）

用法:
    # 命令行传参
    python image_to_c.py my_digit.png
    python image_to_c.py my_digit.png --out my_digit.h --name my_digit

    # 或者改下面 main() 里的 HARDCODE_MODE = True
    python image_to_c.py
"""

import sys
import argparse
import numpy as np
from PIL import Image

# ============ 硬编码模式开关 ============
HARDCODE_MODE = True          # ← True 时用下面的路径，False 时用命令行参数

HARDCODE_IMG_PATH = r"D:\fpgafile\e203_cnn\py\my_digit.png"      #图像地址
HARDCODE_OUT_FILE = "manwrite.h"
HARDCODE_VAR_NAME = "manwrite"
HARDCODE_THRESHOLD = None      # 例如 128


def image_to_array(path, invert=None, threshold=None):
    img = Image.open(path).convert('L')
    img = img.resize((28, 28), Image.LANCZOS)
    arr = np.array(img, dtype=np.uint8)

    if invert is None:
        corners = np.concatenate([
            arr[0:3, 0:3].flatten(),
            arr[0:3, -3:].flatten(),
            arr[-3:, 0:3].flatten(),
            arr[-3:, -3:].flatten(),
        ])
        if corners.mean() > 128:
            print(f"[INFO] 检测到背景偏亮，自动反色")
            arr = 255 - arr
    elif invert:
        arr = 255 - arr

    if threshold is not None:
        arr = np.where(arr > threshold, 255, 0).astype(np.uint8)

    return arr


def print_c_array(arr, name='my_digit'):
    print(f'\n// {name} (28x28, uint8)')
    print(f'static const unsigned char {name}[28][28] = {{')
    for r in range(28):
        row = ', '.join(f'{int(v):3d}' for v in arr[r])
        print(f'    {{{row}}},')
    print('};')


def save_c_header(arr, filename, name='my_digit'):
    with open(filename, 'w') as f:
        f.write('// Auto-generated by image_to_c.py\n')
        f.write('#ifndef MY_DIGIT_H\n#define MY_DIGIT_H\n\n')
        f.write('#include <stdint.h>\n\n')
        f.write(f'static const unsigned char {name}[28][28] = {{\n')
        for r in range(28):
            row = ', '.join(f'{int(v):3d}' for v in arr[r])
            f.write(f'    {{{row}}},\n')
        f.write('};\n\n')
        f.write('#endif // MY_DIGIT_H\n')
    print(f'\n[OK] 已保存到 {filename}')


def print_ascii_art(arr):
    print('\n=== ASCII 预览 ===')
    chars = ' .:-=+*#%@'
    for r in range(28):
        line = ''
        for c in range(28):
            v = arr[r][c]
            idx = v * (len(chars) - 1) // 255
            line += chars[idx]
        print(line)
    print('==================\n')


def main():
    if HARDCODE_MODE:
        # ============ 硬编码模式 ============
        arr = image_to_array(HARDCODE_IMG_PATH, invert=None, threshold=HARDCODE_THRESHOLD)
        print(f'[INFO] 输入: {HARDCODE_IMG_PATH}')
        print(f'[INFO] 尺寸: {arr.shape}')
        print(f'[INFO] 灰度范围: min={arr.min()}, max={arr.max()}, mean={arr.mean():.1f}')
        print_ascii_art(arr)
        print_c_array(arr, HARDCODE_VAR_NAME)
        save_c_header(arr, HARDCODE_OUT_FILE, HARDCODE_VAR_NAME)
    else:
        # ============ 命令行模式 ============
        parser = argparse.ArgumentParser(description='图片转 C 数组')
        parser.add_argument('image', help='输入图片路径')
        parser.add_argument('--invert', action='store_true', help='强制反色')
        parser.add_argument('--no-invert', action='store_true', help='不反色')
        parser.add_argument('--threshold', type=int, default=None,
                            help='二值化阈值（0-255）')
        parser.add_argument('--out', default='my_digit.h', help='输出 .h 文件名')
        parser.add_argument('--name', default='my_digit', help='C 数组变量名')
        args = parser.parse_args()

        if args.invert and args.no_invert:
            print('ERROR: --invert 和 --no-invert 不能同时用')
            sys.exit(1)

        invert = None if not (args.invert or args.no_invert) else args.invert

        arr = image_to_array(args.image, invert=invert, threshold=args.threshold)

        print(f'[INFO] 输入: {args.image}')
        print(f'[INFO] 尺寸: {arr.shape}')
        print(f'[INFO] 灰度范围: min={arr.min()}, max={arr.max()}, mean={arr.mean():.1f}')

        print_ascii_art(arr)
        print_c_array(arr, args.name)
        save_c_header(arr, args.out, args.name)


if __name__ == '__main__':
    main()